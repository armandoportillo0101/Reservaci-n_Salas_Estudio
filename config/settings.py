def _build_database_config() -> dict:
    """Construye la configuración de base de datos desde el entorno."""
    engine = os.environ.get("DB_ENGINE", "django.db.backends.sqlite3")
    if " sqlite" in engine or engine.endswith("sqlite3"):
        db_name = os.environ.get("DB_NAME", "db.sqlite3")
        return {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / db_name,
            "OPTIONS": {
                "transaction_mode": "IMMEDIATE",
                "timeout": 20,
            },
            "TEST": {
                "NAME": BASE_DIR / "test_db.sqlite3",
            },
        }
    return {
        "ENGINE": engine,
        "NAME": os.environ.get("DB_NAME", "reservaciones_db"),
        "USER": os.environ.get("DB_USER", "postgres"),
        "PASSWORD": os.environ.get("DB_PASSWORD", "postgres"),
        "HOST": os.environ.get("DB_HOST", "localhost"),
        "PORT": os.environ.get("DB_PORT", "5432"),
    }


